#!/usr/bin/env node
/**
 * Generates js/data-chapters-meta.js — a lightweight version of data-chapters.js
 * with sections[].content stripped to null.
 * This is loaded eagerly on every page; the full data-chapters.js is lazy-loaded
 * only when a user actually opens a chapter.
 *
 * Usage: node tools/build-chapters-meta.js
 */
const fs = require('fs');
const path = require('path');
const vm   = require('vm');

const fullPath = path.join(__dirname, '../js/data-chapters.js');
const metaPath = path.join(__dirname, '../js/data-chapters-meta.js');

// Evaluate the file — it may use 'const' or 'window.CHAPTERS' depending on which
// version is already on disk. Normalise both.
let src = fs.readFileSync(fullPath, 'utf8');
// Replace leading `const CHAPTERS` or `window.CHAPTERS` so vm can grab the value.
src = src.replace(/^(window\.CHAPTERS\s*=|const CHAPTERS\s*=)\s*/m, 'CHAPTERS = ');

const sandbox = { CHAPTERS: undefined };
vm.createContext(sandbox);
vm.runInContext(src, sandbox);

if (!Array.isArray(sandbox.CHAPTERS)) {
  console.error('Could not parse CHAPTERS from', fullPath);
  process.exit(1);
}

const meta = sandbox.CHAPTERS.map(ch => ({
  id:       ch.id,
  icon:     ch.icon,
  color:    ch.color,
  title:    ch.title,
  subtitle: ch.subtitle,
  intro:    ch.intro,
  readTime: ch.readTime,
  checklist: ch.checklist || [],
  sections: (ch.sections || []).map(sec => ({
    icon:    sec.icon  || null,
    title:   sec.title || null,
    content: null          // stripped — loaded lazily from data-chapters.js
  }))
}));

const out = [
  '/* AUTO-GENERATED by tools/build-chapters-meta.js — do not edit directly */',
  '/* Full content lives in data-chapters.js and is loaded lazily.           */',
  'window.CHAPTERS = ' + JSON.stringify(meta, null, 0) + ';',
  ''
].join('\n');

fs.writeFileSync(metaPath, out, 'utf8');

const fullBytes = fs.statSync(fullPath).size;
const metaBytes = Buffer.byteLength(out, 'utf8');
console.log(`Written ${metaPath}`);
console.log(`  Full file : ${(fullBytes / 1024).toFixed(0)} KB`);
console.log(`  Meta file : ${(metaBytes / 1024).toFixed(0)} KB`);
console.log(`  Savings   : ${(((fullBytes - metaBytes) / fullBytes) * 100).toFixed(0)}%`);
