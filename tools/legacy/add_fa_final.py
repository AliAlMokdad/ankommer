def process():
    content = read_file()
    print('File length:', len(content))

    ur_count = content.count('ur:`')
    print('ur: backtick count:', ur_count)

    not_found = []
    found_count = 0

    # Build list of (position_of_end, fa_text) - end means position of the backtick in ` }
    insertions = []

    for snippet, fa_text in FA_MAP.items():
        # Find the snippet in the file
        pos = content.find(snippet)
        if pos == -1:
            not_found.append(snippet[:80])
            continue

        # Now find the `ur:` that contains this snippet
        # Scan backwards from pos to find 'ur:`'
        ur_start = content.rfind('ur:`', 0, pos)
        if ur_start == -1:
            print('No ur: found before snippet:', snippet[:60])
            continue

        # Find the closing ` } of this ur: block
        ur_content_start = ur_start + 4
        close_pos = content.find('` }', ur_content_start)
        if close_pos == -1:
            print('No closing found for:', snippet[:60])
            continue

        # Verify snippet is within this block
        if pos > close_pos:
            print('Snippet is AFTER closing backtick:', snippet[:60])
            continue

        # The insertion point: right after the backtick of ` }
        # content[close_pos] = '`', content[close_pos+1] = ' ', content[close_pos+2] = '}'
        insert_pos = close_pos + 1  # after the backtick, before ' }'

        insertions.append((insert_pos, fa_text, snippet[:40]))
        found_count += 1

    print('Found snippets:', found_count)
    print('Not found:', len(not_found))
    for nf in not_found:
        print('  NOT FOUND:', nf)

    # Sort by position descending (to avoid index shifting)
    insertions.sort(key=lambda x: x[0], reverse=True)

    # Apply insertions
    for insert_pos, fa_text, desc in insertions:
        # Insert: ,\n          fa:`<text>`
        insert_str = ',\n          fa:`' + fa_text + '`'
        content = content[:insert_pos] + insert_str + content[insert_pos:]

    write_file(content)

    fa_count = content.count('fa:`')
    print('fa: backtick count after:', fa_count)
    print('Done!')

if __name__ == '__main__':
    process()
