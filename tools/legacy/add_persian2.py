def find_ur_block_end(content, snippet_pos):
    """Find the end of the ur: backtick block that contains snippet_pos.
    The block starts with 'ur:`' somewhere before snippet_pos.
    We need to find the backtick that closes the template literal after snippet_pos.
    Returns the position AFTER the closing backtick.
    """
    # Find the closing backtick
    # Template literals end with a backtick not preceded by backslash
    pos = snippet_pos
    while pos < len(content):
        if content[pos] == '`' and (pos == 0 or content[pos-1] != '\\'):
            return pos + 1  # position after the closing backtick
        pos += 1
    return -1

def process_file():
    content = read_file()
    print(f"File length: {len(content)} chars")

    ur_count = content.count('ur:`')
    print(f"ur: backtick count: {ur_count}")

    # Process translations in order of their occurrence in the file
    # Build a list of (position, fa_text) to insert
    insertions = []
    not_found = []

    for snippet, fa_text in FA_TRANSLATIONS.items():
        if fa_text is None:
            continue  # Skip placeholder entries

        pos = content.find(snippet)
        if pos == -1:
            not_found.append(snippet[:80])
            continue

        # Find the end of the ur: block containing this snippet
        end_pos = find_ur_block_end(content, pos + len(snippet))
        if end_pos == -1:
            print(f"Could not find end of ur: block for: {snippet[:60]}")
            continue

        insertions.append((end_pos, fa_text))

    print(f"Found: {len(insertions)} translations to insert")
    print(f"Not found: {len(not_found)}")
    for nf in not_found:
        print(f"  NOT FOUND: {nf}")

    # Sort insertions by position (REVERSE order so indices don't shift)
    insertions.sort(key=lambda x: x[0], reverse=True)

    # Apply insertions
    for pos, fa_text in insertions:
        insert_str = f",\n          fa:`{fa_text}`"
        content = content[:pos] + insert_str + content[pos:]

    # Write result
    write_file(content)

    fa_count = content.count('fa:`')
    print(f"fa: backtick count after: {fa_count}")
    print("Done!")

if __name__ == '__main__':
    process_file()
