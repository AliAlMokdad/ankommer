def process():
    with open(FILE_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    print('ur: string count:', len(re.findall(r'ur:"[^"]*"', content)))
    print('fa: string count before:', len(re.findall(r'fa:"[^"]*"', content)))

    # Find all ur: string occurrences and their positions
    # Pattern: ur:"..."
    matches = list(re.finditer(r'ur:"([^"]*)"', content))
    print(f'Found {len(matches)} ur: string matches')

    not_found_translations = []
    insertions = []

    for m in matches:
        ur_text = m.group(1)
        if ur_text not in FA_STRINGS:
            not_found_translations.append(ur_text[:60])
            continue

        fa_text = FA_STRINGS[ur_text]
        # Insert after the ur:"..." string
        insert_pos = m.end()
        insert_str = ', fa:"' + fa_text + '"'
        insertions.append((insert_pos, insert_str))

    if not_found_translations:
        print(f'Missing translations for {len(not_found_translations)} entries:')
        for t in not_found_translations:
            print(f'  {repr(t)}')

    # Sort descending
    insertions.sort(key=lambda x: x[0], reverse=True)

    # Apply
    for insert_pos, insert_str in insertions:
        content = content[:insert_pos] + insert_str + content[insert_pos:]

    with open(FILE_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    fa_string_count = len(re.findall(r'fa:"[^"]*"', content))
    print(f'fa: string count after: {fa_string_count}')
    print('Done!' if fa_string_count == 48 else f'WARNING: Expected 48, got {fa_string_count}')

if __name__ == '__main__':
    process()
